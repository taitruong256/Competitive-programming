#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;
ll n, k, dp[50005][505], dp2[50005], ans;
vector<ll> adj[50005];

void dfs(ll u, ll p)
{
    dp[u][0]=1;
    for (auto v: adj[u]) if (v!=p)
    {
        dfs(v, u);
        for (ll i=1; i<=k-1; i++) ans+=dp[u][i]*dp[v][k-1-i]; 
        for (ll i=0; i<=k-1; i++) dp[u][i+1]+=dp[v][i];
    }
    
}

void solve()
{
    cin>>n>>k;
    for (ll i=1; i<=n-1; i++)
    {
        ll u, v; cin>>u>>v;
        adj[u].push_back(v);
        adj[v].push_back(u);
    }
    dfs(1, -1);
    for (ll i=1; i<=n; i++) ans+=dp[i][k];
    cout<<ans;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}