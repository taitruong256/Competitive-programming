#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll inf = 1e18;
const ll mod = 1e9+7;

void setIO(string s)
{
    freopen((s+".in").c_str(), "r", stdin);
    freopen((s+".out").c_str(), "w", stdout);
}
void solve()
{
    // setIO("king2");
    vector<vector<ll>> dp(20, vector<ll> (20)), a(20, vector<ll> (20));
    for (ll i=1; i<=8; i++)
        for (ll j=1; j<=8; j++) cin>>a[i][j];
    for (ll i=0; i<=9; i++)
        for (ll j=0; j<=9; j++) dp[i][j]=1e18;
    dp[9][0]=0;
    for (ll i=8; i>=1; i--)
        for (ll j=1; j<=8; j++) 
        {
            dp[i][j]=min({dp[i+1][j], dp[i][j-1], dp[i+1][j-1]})+a[i][j];
        }
    cout<<dp[1][8];
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}