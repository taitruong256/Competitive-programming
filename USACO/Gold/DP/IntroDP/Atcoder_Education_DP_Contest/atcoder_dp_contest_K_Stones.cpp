#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll inf = 1e18;
const ll mod = 1e9+7;

void solve()
{
    ll n, k; cin>>n>>k;
    bool dp[k+5];
    ll a[n+5];
    for (ll i=1; i<=n; i++) cin>>a[i];
    for (ll i=0; i<=k; i++) dp[i]=false;
    for (ll i=1; i<=k; i++)
        for (ll j=1; j<=n; j++) if (i>=a[j] && dp[i-a[j]]==false) dp[i]=true;
    if (dp[k]==true) cout<<"First";
    else cout<<"Second";
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}