#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll inf = 1e18;
const ll mod = 1e9+7;
const ll maxn = 1e5+5;
vector<ll> adj[maxn];
ll dp[maxn][3], n;  //1: den    2: trang

ll add(ll x, ll y)
{
    return (x+y)%mod;
}

ll mul(ll x, ll y)
{
    return (x*y)%mod;
}

void dfs(ll u, ll par)
{
    dp[u][1]=1;
    dp[u][2]=1;
    for (auto v: adj[u]) if (v!=par)
    {
        dfs(v, u);
        dp[u][1]=mul(dp[u][1], dp[v][2]);
        dp[u][2]=mul(dp[u][2], add(dp[v][1], dp[v][2]));
    }
}

void solve()
{
    cin>>n;
    for (ll i=0; i<n-1; i++)
    {
        ll u, v; cin>>u>>v;
        adj[u].push_back(v);
        adj[v].push_back(u);
    }
    dfs(1, 1);
    cout<<(dp[1][1]+dp[1][2])%mod;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}