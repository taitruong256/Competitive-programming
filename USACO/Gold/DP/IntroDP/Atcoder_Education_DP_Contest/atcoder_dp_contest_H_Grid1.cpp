#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll inf = 1e18;
const ll mod = 1e9+7;
string s[1005];
ll dp[1005][1005];

void solve()
{
    ll n, m; cin>>n>>m;
    for (ll i=1; i<=n; i++)
    {
        cin>>s[i];
        s[i]=" "+s[i];
    }
    if (s[1][1]=='.') dp[1][1]=1;
    else dp[1][1]=0;
    for (ll i=1; i<=n; i++)
    {
        for (ll j=1; j<=m; j++)
        {
            if (i==1 && j==1) continue;
            if (s[i][j]=='#') dp[i][j]=0;
            else dp[i][j]=(dp[i-1][j]+dp[i][j-1])%mod;
        }
    }
    cout<<dp[n][m];
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}