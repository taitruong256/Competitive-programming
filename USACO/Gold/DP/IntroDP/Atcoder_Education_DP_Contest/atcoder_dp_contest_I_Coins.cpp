#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll inf = 1e18;
const ll mod = 1e9+7;
double dp[3005][3005], p[3005];

void solve()
{
    ll n; cin>>n;
    for (ll i=1; i<=n; i++) cin>>p[i];
    dp[0][0]=1.0;
    for (ll i=1; i<=n; i++)
    {
        for (ll j=0; j<=n; j++) 
        {
            if (j==0) dp[i][j]=dp[i-1][j]*(1.0-p[i]);
            else dp[i][j]=dp[i-1][j-1]*p[i]+dp[i-1][j]*(1.0-p[i]);
        }
    }
    double ans=0;
    for (ll i=n/2+1; i<=n; i++) ans+=dp[n][i];
    cout<<fixed<<setprecision(9)<<ans;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}