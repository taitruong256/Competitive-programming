#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll inf = 1e18;
const ll mod = 1e9+7;
ll n, k, dp[105][100005], a[105];

void solve()
{
    cin>>n>>k;
    for (ll i=1; i<=n; i++) cin>>a[i];
    dp[0][0]=1;
    for (ll i=1; i<=n; i++)
    {
        vector<ll> sum(k+5);
        sum[0]=dp[i-1][0];
        for (ll j=1; j<=k; j++) sum[j]=(sum[j-1]+dp[i-1][j])%mod;
        for (ll j=0; j<=k; j++)
            if (j<=a[i])
                dp[i][j]=sum[j];
            else 
                dp[i][j]=(sum[j]-sum[j-a[i]-1]+mod)%mod;
    }
    cout<<dp[n][k];
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}