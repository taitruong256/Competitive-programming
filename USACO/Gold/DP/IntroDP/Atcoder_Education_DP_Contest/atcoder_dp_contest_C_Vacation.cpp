#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll inf = 1e18;
const ll mod = 1e9+7;

void solve()
{
    ll n; cin>>n;
    vector<vector<ll>> a(n+5, vector<ll> (4)), dp(n+5, vector<ll> (4));
    for (ll i=1; i<=n; i++)
        for (ll j=1; j<=3; j++) cin>>a[i][j];
    for (ll i=1; i<=n; i++)
    {
        dp[i][1]=max(dp[i-1][2], dp[i-1][3])+a[i][1];
        dp[i][2]=max(dp[i-1][1], dp[i-1][3])+a[i][2];
        dp[i][3]=max(dp[i-1][1], dp[i-1][2])+a[i][3];
    }
    cout<<max({dp[n][1], dp[n][2], dp[n][3]});
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}