#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll inf = 1e18;
const ll mod = 1e9+7;

void setIO(string s)
{
    freopen((s+".in").c_str(), "r", stdin);
    freopen((s+".out").c_str(), "w", stdout);
}
ll dp[2][5000005];

void solve()
{
    setIO("feast");
    ll t, a, b; cin>>t>>a>>b;
    dp[0][0]=1;
    for (ll i=0; i<=t; i++)
    {
        if (i>=a) dp[0][i]|=dp[0][i-a];
        if (i>=b) dp[0][i]|=dp[0][i-b];
        dp[1][i/2]|=dp[0][i];
    }
    for (ll i=0; i<=t; i++)
    {
        if (i>=a) dp[1][i]|=dp[1][i-a];
        if (i>=b) dp[1][i]|=dp[1][i-b];
    }
    for (ll i=t; i>=0; i--) if (dp[1][i]==1)
    {
        cout<<i;
        return;
    }
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}