#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll inf = 1e18;
const ll mod = 1e9+7;

void setIO(string s)
{
    freopen((s+".in").c_str(), "r", stdin);
    freopen((s+".out").c_str(), "w", stdout);
}
void solve()
{
    setIO("help");
    ll n; cin>>n;
    vector<ll> pref(2*n+5), pw(2*n+5);
    for (ll i=1; i<=n; i++)
    {
        ll l, r; cin>>l>>r;
        ++pref[l];
        --pref[r];
    }
    pw[0]=1;
    for (ll i=1; i<=2*n; i++) pw[i]=(pw[i-1]*2)%mod;
    ll ans=0, open=0;
    for (ll i=1; i<=2*n; i++)
    {
        open+=pref[i];
        if (pref[i]==1) ans=(ans+pw[n-open])%mod;
    }
    cout<<ans;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}