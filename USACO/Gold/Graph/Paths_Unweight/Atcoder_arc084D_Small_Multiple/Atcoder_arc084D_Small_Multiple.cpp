#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;
ll k, dist[100005];
deque<ll> dq;

void solve()
{
    cin>>k;
    for (ll i=0; i<=k; i++) dist[i]=1e18;
    dist[1]=1;
    dq.push_back(1);
    while (!dq.empty())
    {
        auto x=dq.front(); dq.pop_front();
        if (dist[x]<dist[(x*10)%k])
        {
            dist[(x*10)%k]=dist[x];
            dq.push_front((x*10)%k);
        }
        if (dist[x]+1<dist[(x+1)%k])
        {
            dist[(x+1)%k]=dist[x]+1;
            dq.push_back((x+1)%k);
        }
    }
    cout<<dist[0];
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}