#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;

struct point 
{
    ll x, y;
};  

bool comp(point A, point B)
{
    return atan2l(A.y, A.x)<atan2l(B.y, B.x);
}

void solve()
{
    ll n; cin>>n;
    point p[n+5];
    for (ll i=1; i<=n; i++) cin>>p[i].x>>p[i].y;
    sort(p+1, p+n+1, comp);
    for (ll i=1; i<=n; i++) cout<<p[i].x<<" "<<p[i].y<<endl;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}