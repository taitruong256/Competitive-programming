#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;
ll n;
bitset<3005> a[3005];

void solve()
{
    cin>>n;
    for (ll i=1; i<=n; i++)
        for (ll j=1; j<=n; j++)
        {
            char c; cin>>c;
            if (c=='1') a[i][j]=a[j][i]=1;
        }
    
    ll ans=0;
    for (ll i=1; i<=n-1; i++)
        for (ll j=i+1; j<=n; j++)
            if (a[i][j]==1)
                ans+=(a[i]&a[j]).count();
    cout<<ans/3;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}