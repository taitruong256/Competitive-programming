#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'

void solve()
{
    ll n; cin>>n;
    if (n==1)
    {
        cout<<0;
        return;
    }
    ll f[100];
    f[1]=2;
    f[2]=3;
    for (ll i=3; i<=87; i++) f[i]=f[i-1]+f[i-2];
    ll ans=0;
    for (ll i=1; i<=87; i++) if (f[i]<=n) ans=i;
    cout<<ans;
}
 
int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}