#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll inf = 1e18;
const ll mod = 1e9+7;

void setIO(string s)
{
    freopen((s+".in").c_str(), "r", stdin);
    freopen((s+".out").c_str(), "w", stdout);
}
void solve()
{
    setIO("blist");
    ll n; cin>>n;
    vector<ll> pref(1005);
    for (ll i=0; i<n; i++)
    {
        ll x, y, t; cin>>x>>y>>t;
        pref[x]+=t;
        pref[y+1]-=t;
    }
    ll ans=0;
    for (ll i=1; i<=1000; i++) pref[i]+=pref[i-1], ans=max(ans, pref[i]);
    cout<<ans;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}