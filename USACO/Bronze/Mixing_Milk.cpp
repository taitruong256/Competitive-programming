#include <bits/stdc++.h>
#include <ext/pb_ds/assoc_container.hpp>
#include <ext/pb_ds/tree_policy.hpp>
using namespace std;
using namespace __gnu_pbds;
#define ll long long
#define ordered_set tree<ll, null_type, less<ll>, rb_tree_tag, tree_order_statistics_node_update>
#define endl '\n'
const ll mod = 1e9+7;
const ll inf = 1e9;
ll n=3;
ll c[5], m[5];

void dosua(ll nguon, ll dich)
{
    ll sl=min(m[nguon], c[dich]-m[dich]);
    m[nguon]-=sl;
    m[dich]+=sl;
}

void solve()
{
    for (ll i=0; i<3; i++) cin>>c[i]>>m[i];
    for (ll i=0; i<100; i++) dosua(i%n, (i+1)%n);
    for (ll i=0; i<3; i++) cout<<m[i]<<endl;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("mixmilk.in", "r", stdin);
    freopen("mixmilk.out", "w", stdout);
    #endif
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}