#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;

void solve()
{
    ll n, k; cin>>n>>k;
    string line; cin>>line;
    ll space=0;
    for (ll i=1; i<n; i++)
    {
        fflush(stdin);
        string s; cin>>s; 
        if (line.size()+s.size()-space<=k) line=line+" "+s, ++space; 
        else cout<<line<<endl, line=s, space=0;
    }
    cout<<line;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("word.in", "r", stdin);
    freopen("word.out", "w", stdout);
    #endif
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}