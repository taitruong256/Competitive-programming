#define endl '\n'
const ll mod = 1e9+7;
const ll inf = 1e9;
const ll maxn = 2e5+5;

void solve()
{
    ll n, k; cin>>n>>k;
    ll a[n+5];
    for (ll i=1; i<=n; i++) cin>>a[i];
    ll ans=1e9;
    for (ll i=1; i<=a[1]; i++)
    {
        ll mx=i;
        for (ll j=1; j<=n; j++)
        {
            ll p=min(k, a[j]/i);
            mx=max(mx, a[j]/p);
        }
        ans=min(ans, mx-i);
    }
    cout<<ans<<endl;
}

