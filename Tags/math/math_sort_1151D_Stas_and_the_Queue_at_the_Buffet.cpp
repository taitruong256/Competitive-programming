#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;
pair<ll, ll> a[100005];

bool comp(pair<ll, ll> a, pair<ll, ll> b)
{
    return a.first-a.second>b.first-b.second;
}

void solve()
{
    ll n; cin>>n;
    for (ll i=1; i<=n; i++) cin>>a[i].first>>a[i].second;
    ll ans=0;
    for (ll i=1; i<=n; i++) ans+=a[i].second*n-a[i].first;
    sort(a+1, a+n+1, comp);
    for (ll i=1; i<=n; i++) ans+=(a[i].first-a[i].second)*i;
    cout<<ans<<endl;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}