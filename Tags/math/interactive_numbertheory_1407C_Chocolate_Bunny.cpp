#include <bits/stdc++.h>
using namespace std;
#define ll long long
const ll mod = 1e9+7;

ll query(ll x, ll y)
{
    cout<<"? "<<x<<" "<<y<<endl;
    ll t; cin>>t;
    return t;
}

void solve()
{
    ll n; cin>>n;
    ll mx=1, ans[n+5];
    for (ll i=2; i<=n; i++)
    {
        ll x=query(mx, i);
        ll y=query(i, mx);
        if (x>y)
        {
            ans[mx]=x;
            mx=i;
        }
        else 
        {
            ans[i]=y;
        }
    }
    ans[mx]=n;
    cout<<"! ";
    for (ll i=1; i<=n; i++) cout<<ans[i]<<" ";
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}