#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;

void solve()
{
    ll h, c, t; cin>>h>>c>>t;
    if (t<=(h+c)/2)
    {
        cout<<2<<endl;
        return;
    }
    ll x=(h-t)/(2*t-h-c);
    x=2*x+1;
    ll sum=1e12, cnt=1, ans=-1;
    for (ll i=max(1LL, x-1000); i<=x+1000; i+=2) 
    {
        ll s=abs((i/2+1)*h+i/2*c-t*i);
        if (s*cnt<i*sum)
        {
            sum=s;
            cnt=i;
            ans=i;
        } 
    }
    assert(ans!=-1);
    cout<<ans<<endl;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    ll t; cin>>t;
    while (t--) solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}