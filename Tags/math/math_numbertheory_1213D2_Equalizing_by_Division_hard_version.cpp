#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;
vector<ll> cnt[200005];

void solve()
{
    ll n, k; cin>>n>>k;
    ll a[n+5];
    for (ll i=1; i<=n; i++) cin>>a[i];
    for (ll i=1; i<=n; i++)
    {
        ll x=a[i], sobuoc=0;
        while (x>0)
        {
            cnt[x].push_back(sobuoc);
            x/=2;
            sobuoc+=1;
        }
    }
    ll ans=1e18;
    for (ll i=1; i<=200000; i++) sort(cnt[i].begin(), cnt[i].end());
    for (ll i=1; i<=200000; i++) if (cnt[i].size()>=k) 
    {
        ll s=0;
        for (ll j=0; j<k; j++) s+=cnt[i][j];
        ans=min(ans, s);
    }
    assert(ans!=1e18);
    cout<<ans;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}