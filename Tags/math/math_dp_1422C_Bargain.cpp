#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;

void solve()
{
    string s; cin>>s; s=" "+s;
    ll n=s.size()-1;
    ll ans=0, sum=0, pw=1, suff=0;
    for (ll i=n; i>=1; i--)
    {
        ans=(ans + (i*(i-1)/2%mod*pw%mod + sum)*(s[i]-'0'))%mod;
        suff=(suff+pw)%mod;
        pw=(pw*10)%mod;
        sum=(sum*10+suff)%mod;   
    }
    cout<<ans;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}