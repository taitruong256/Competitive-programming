#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;
ll n, pref[3005], suff[3005], a[3005];

void solve()
{
    cin>>n;
    for (ll i=1; i<=n; i++) cin>>a[i];
    ll ans=0;
    for (ll j=1; j<=n-1; j++)
    {
        for (ll i=1; i<=n; i++) suff[i]=0;
        for (ll k=n; k>=j+1; k--)
        {       
            ans+=pref[a[k]]*suff[a[j]];
            ++suff[a[k]];
        }
        ++pref[a[j]];
    }
    for (ll i=1; i<=n; i++) pref[i]=suff[i]=0;
    cout<<ans<<endl;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    ll t; cin>>t;
    while (t--) solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}