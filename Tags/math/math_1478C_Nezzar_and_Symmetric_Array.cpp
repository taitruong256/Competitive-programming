#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;

void solve()
{
    ll n; cin>>n;
    ll d[2*n+5];
    for (ll i=1; i<=2*n; i++) cin>>d[i];
    d[2*n+1]=1e18;
    sort(d+1, d+2*n+1);
    for (ll i=1; i<=2*n; i+=2) 
    {
        if (!(d[i]==d[i+1] && d[i]!=d[i+2]))
        {
            cout<<"NO\n";
            return;
        }
    }
    ll sum=0, x;
    for (ll i=2*n; i>=1; i-=2)
    {
        if ((d[i]-2*sum)%i!=0)
        {
            cout<<"NO\n";
            return;
        }
        x=(d[i]-2*sum)/i;
        sum+=x;
    }
    if (x<=0) cout<<"NO\n";
    else cout<<"YES\n";
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    ll t; cin>>t;
    while (t--) solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}