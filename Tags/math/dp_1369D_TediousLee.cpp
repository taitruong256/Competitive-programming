#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;
ll dp[2000005];

void solve()
{
    ll n; cin>>n;
    cout<<dp[n]<<endl;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    dp[3]=4;
    dp[4]=4;
    for (ll i=5; i<=2000000; i++) 
        if (i%3==0) dp[i]=(4+dp[i-2]+4*dp[i-3]+4*dp[i-4])%mod;
        else dp[i]=(dp[i-1]+2*dp[i-2])%mod;
    ll t; cin>>t;
    while (t--) solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}