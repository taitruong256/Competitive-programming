#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;

void solve()
{
    ll d, k; cin>>d>>k;
    ll x=0, y=0;
    while (true)
    {
        if (x<=y && (x+k)*(x+k)+y*y<=d*d) x+=k;
        else if (x>y && x*x+(y+k)*(y+k)<=d*d) y+=k;
        else break;
    }
    if (x==y) cout<<"Utkarsh\n";
    else cout<<"Ashish\n";
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    ll t; cin>>t;
    while (t--) solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}