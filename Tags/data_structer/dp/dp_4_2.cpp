#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;
ll dp[105][20105], v[105];

void solve()
{
    ll n, s, mx=0; cin>>n>>s;
    for (ll i=1; i<=n; i++) cin>>v[i], mx=max(mx, v[i]);
    ll ans=0;
    if (s>=20000) ans=(s-20000)/mx, s-=ans*mx;
    for (ll i=0; i<=n; i++) dp[i][0]=0;
    for (ll i=1; i<=s; i++) dp[0][i]=1e18;
    for (ll i=1; i<=n; i++) 
        for (ll j=1; j<=s; j++) if (j>=v[i]) 
            dp[i][j]=min(dp[i-1][j], dp[i][j-v[i]]+1);
            else dp[i][j]=dp[i-1][j];
    cout<<ans+dp[n][s];
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}