#include <bits/stdc++.h>
using namespace std;
typedef long long ll;

void solve()
{
    ll n; cin>>n;
    ll a[n+5];
    map<ll, ll> last;
    ll ans=-1;
    for (ll i=1; i<=n; i++)
    {
        ll x; cin>>x;
        if (last[x]) ans=max(ans, n-i+last[x]);
        last[x]=i;
    }
    cout<<ans<<endl;
}
