#include <bits/stdc++.h>
using namespace std;
typedef long long ll;

void solve()
{
    ll n; cin>>n;
    string s; cin>>s;
    ll ans=0, sum=0;
    map<ll, ll> cnt; 
    cnt[0]=1;
    for (ll i=0; i<s.size(); i++)
    {
        sum+=(s[i]-'0');
        ans+=cnt[sum-i-1];
        cnt[sum-i-1]++;
    }
    cout<<ans<<endl;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    ll t; cin>>t;
    while (t--) solve();
    return 0;
}