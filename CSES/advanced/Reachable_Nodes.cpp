#include <bits/stdc++.h>
#pragma GCC optimize("O3,unroll-loops")
#pragma GCC target("avx2,bmi,bmi2,lzcnt,popcnt")
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;
ll n, m;
vector<ll> adj[50005];
bool vis[50005];
bitset<50005> dp[50005];

void dfs(ll u)
{                
    vis[u]=true;
    dp[u].set(u, 1);
    for (auto v: adj[u])
    {                   
        if (vis[v]==false) dfs(v);
        dp[u]|=dp[v];
    }           
}

void solve()
{
    cin>>n>>m;
    for (ll i=1; i<=m; i++)
    {
        ll u, v; cin>>u>>v;
        adj[u].push_back(v);
    }
    for (ll i=1; i<=n; i++) if (vis[i]==false) dfs(i);
    for (ll i=1; i<=n; i++) cout<<dp[i].count()<<" ";
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}