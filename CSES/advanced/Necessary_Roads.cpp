#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;
vector<ll> adj[100005];
ll n, m, num[100005], low[100005], timeDfs=0;
bool vis[100005];
vector<pair<ll, ll>> bridges;

void dfs(ll u, ll par)
{
    vis[u]=true;
    num[u]=low[u]=++timeDfs;
    for (auto v: adj[u])
    {
        if (v==par) continue;
        if (vis[v]==false) 
        {
            dfs(v, u);
            low[u]=min(low[u], low[v]);
            if (low[v]==num[v]) bridges.push_back({u, v});
        }
        else low[u]=min(low[u], num[v]);
    }
}

void solve()
{
    cin>>n>>m;
    for (ll i=0; i<m; i++)
    {
        ll u, v; cin>>u>>v;
        adj[u].push_back(v);
        adj[v].push_back(u);
    }
    dfs(1, 1);
    cout<<bridges.size()<<endl;
    for (auto i: bridges) cout<<i.first<<" "<<i.second<<endl;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}