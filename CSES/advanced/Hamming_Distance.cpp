#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;

void solve()
{
    ll n, k; cin>>n>>k;
    vector<ll> v;
    for (ll i=0; i<n; i++)
    {
        string s; cin>>s;
        ll x=0;
        for (ll i=0; i<k; i++) x+=(s[i]-'0')*(1<<i);
        v.push_back(x);
    }

    ll ans=k;
    for (ll i=0; i<v.size()-1; i++)
        for (ll j=i+1; j<v.size(); j++) ans=min(ans, (ll)__builtin_popcountll(v[i]^v[j]));
    cout<<ans;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}