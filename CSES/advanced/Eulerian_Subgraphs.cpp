#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;
ll n, m, vis[100005], cnt;
vector<ll> adj[100005];

ll binpow(ll x, ll n, ll mod)
{
    ll ans=1;
    while (n>0)
    {
        if (n%2==1) ans=(ans*x)%mod;
        x=(x*x)%mod;
        n/=2;
    }
    return ans;
}

void dfs(ll u, ll par)
{
    vis[u]=1;
    for (auto v: adj[u]) if (v!=par)
    {
        if (vis[v]==1) ++cnt;
        else if (vis[v]==0) dfs(v, u);
    }
    vis[u]=2;
}

void solve()
{
    cin>>n>>m;
    for (ll i=0; i<m; i++)
    {
        ll u, v; cin>>u>>v;
        adj[u].push_back(v);
        adj[v].push_back(u);
    }

    ll ans=1;
    for (ll i=1; i<=n; i++) if (vis[i]==0)
    {
        cnt=0;  
        dfs(i, i);  
        ans=(ans*binpow(2, cnt, mod))%mod;
    }
    cout<<ans;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}