#include <bits/stdc++.h>
using namespace std;
#define endl '\n'
#define ll long long

void solve()
{
    ll n; cin>>n;
    for (ll i=0; i<(1<<n); i++)
    {
        ll x=i^(i>>1);
        for (ll j=n-1; j>=0; j--) if (x&(1<<j)) cout<<1; else cout<<0;
        cout<<endl;
    }
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    solve();
    return 0;
}