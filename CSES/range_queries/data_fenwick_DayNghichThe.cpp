#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;
const ll inf = 1e9;
ll a[6000005], bit[6000005];
ll n;

void update(ll index, ll value)
{
    for (ll i=index; i<=6e6; i+=-i&i) bit[i]+=value;
}

ll query(ll index)
{
    ll sum=0;
    for (ll i=index; i>=1; i-=-i&i) sum+=bit[i];
    return sum;
}

void solve()
{
    memset(bit, 0, sizeof(bit));
    cin>>n;
    for (ll i=1; i<=n; i++) cin>>a[i];
    ll ans=0;
    for (ll i=n; i>=1; i--)
    {
        ans+=query(a[i]-1);
        update(a[i], 1);
    }
    cout<<ans;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    solve();
    return 0;
}