#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;

void solve()
{
    ll n, l, r; cin>>n>>l>>r;
    ll a[n+5], pref[n+5]={0};
    for (ll i=1; i<=n; i++)
    {
        cin>>a[i];
        pref[i]=pref[i-1]+a[i];
    }
    multiset<ll> ms;
    ll ans=LLONG_MIN;
    for (ll i=1; i<=n; i++)
    {
        if (i>=l) ms.insert(pref[i-l]);
        if (i>r) ms.erase(ms.find(pref[i-r-1]));
        if (i>=l) ans=max(ans, pref[i]-*ms.begin());
    }
    cout<<ans;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}