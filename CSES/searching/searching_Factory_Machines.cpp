#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;
const ll inf = 1e9;
ll n, t; 
ll a[200005];

bool check(ll x)
{
    ll sum=0;
    for (ll i=1; i<=n; i++) 
    {
        sum+=x/a[i];
        if (sum>=t) return true;
    }
    return false;
}

void solve()
{
    cin>>n>>t;
    for (ll i=1; i<=n; i++) cin>>a[i];
    ll l=1, r=1e18, ans=1e18;
    while (l<=r)
    {
        ll mid=(l+r)/2;
        if (check(mid)==true) ans=mid, r=mid-1;
        else l=mid+1;
    } 
    cout<<ans;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    solve();
    return 0;
}