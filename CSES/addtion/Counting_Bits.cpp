#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;

void solve()
{
    ll n; cin>>n;
    ll dp[60];
    dp[0]=0;
    dp[1]=1;
    for (ll i=2; i<60; i++) dp[i]=2*dp[i-1]+(1LL<<(i-1));
    ll ans=0;
    while (n>0)
    {
        ll l=log2(n);
        ans+=dp[l];      
        ll x=(1LL<<l);
        ans+=n-x+1;
        n-=x;
    }
    cout<<ans;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}