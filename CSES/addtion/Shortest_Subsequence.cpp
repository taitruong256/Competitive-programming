#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;

void solve()
{
    string s; cin>>s;
    ll n=s.size();
    string ans="";
    bool has[4];
    memset(has, false, sizeof(has));
    map<char, ll> index;
    index['A']=0;
    index['G']=1;
    index['T']=2;
    index['C']=3;
    ll cnt=0;
    for (ll i=0; i<n; i++)
    {
        ll idx=index[s[i]];
        if (has[idx]==false)
        {
            has[idx]=true;
            ++cnt;
            if (cnt==4)
            {
                ans.push_back(s[i]);
                memset(has, false, sizeof(has));
                cnt=0;
            }
        }
    }
    if (has[0]==false) ans+="A";
    else if (has[1]==false) ans+="G";
    else if (has[2]==false) ans+="T";
    else ans+="C";
    cout<<ans;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}