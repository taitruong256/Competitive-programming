#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;

void solve()
{
    ll n; cin>>n;
    map<ll, ll> cnt;
    ll sum=0;
    while (n>0)
    {
        ll x=sqrt(n);
        ++cnt[x];
        n-=x*x;
        sum+=2;
    }
    for (auto [x, y]: cnt) cout<<x<<" "<<y<<endl; cout<<sum<<endl;
    for (auto &[x, y]: cnt)
    {
        ll val=y;
        if (x==1) continue;
        while (val>=x)
        {
            sum-=val/x*x*2;
            sum+=1;
            val/=x;
        }
    }
    cout<<sum;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}