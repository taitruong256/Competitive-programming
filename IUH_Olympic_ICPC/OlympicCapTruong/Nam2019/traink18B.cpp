void solve()
{
    ll n, k; cin>>n>>k;
    ll a[n+5], sum[n+5];
    for (ll i=1; i<=n; i++) cin>>a[i];
    for (ll i=1; i<=n; i++) a[i]-=k;
    ll s=0;
    map<ll, ll> cnt; 
    for (ll i=1; i<=n; i++)
    {
        s+=a[i];
        ++cnt[s];
    }
    ll ans=0;
    for (auto [x, y]: cnt) 
        if (x!=0) ans+=y*(y-1)/2;
        else ans+=y*(y+1)/2;
    cout<<ans;
}

