#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define ld long double
#define endl '\n'
const ll mod = 1e9+7;

struct DSU
{
    vector<ll> par, size;
    ll n;
    DSU(){}
    DSU(ll _n)
    {
        n=_n;
        par.resize(n+5, 0);
        for (ll i=1; i<=n; i++) par[i]=i;
        size.resize(n+5, 1);
    }
    ll find(ll u)
    {
        if (u==par[u]) return u;
        return par[u]=find(par[u]);   
        }
    bool merge(ll u, ll v)
    {
        u=find(u);
        v=find(v);
        if (u==v) return false;
        if (size[u]<size[v]) swap(u, v);
        par[v]=u;
        size[u]+=size[v];
        return true;
    }
    bool same_component(ll u, ll v)
    {
        return find(u)==find(v);
    }
};
ll n, m, k;
vector<ll> adj[200005], cnt[200005];
map<pair<ll, ll>, ll> used;

void solve()
{
    cin>>n>>m>>k;
    DSU dsu(n);
    for (ll i=0; i<m; i++)
    {
        ll u, v; cin>>u>>v;
        adj[u].push_back(v);
        adj[v].push_back(u);
        dsu.merge(u, v);
    }
    for (ll i=1; i<=n; i++)
    {
        ll deg=adj[i].size();
        ll par=dsu.find(i);
        if (used.find({deg, par})==used.end()) 
        {
            used[{deg, par}]=1;
            cnt[deg].push_back(dsu.size[par]);
        }
    }
    ll ans=0;
    for (ll i=0; i<=m; i++)
    {
        sort(cnt[i].begin(), cnt[i].end(), greater<ll>());
        ll sum=0;
        for (ll j=0; j<min(k, (ll)cnt[i].size()); j++) sum+=cnt[i][j];
        ans=max(ans, sum);
    }
    cout<<ans;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}