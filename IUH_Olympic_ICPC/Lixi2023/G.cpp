#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;
vector<ll> adj[500005];

void solve()
{
    ll n; cin>>n;
    for (ll i=0; i<n-1; i++)
    {
        ll u, v; cin>>u>>v;
        adj[u].push_back(v);
        adj[v].push_back(u);
    }
    ll cnt=0;
    for (ll i=1; i<=n; i++) cnt+=(adj[i].size()>2);
    if (cnt>1) 
    {
        cout<<-1;
        return;
    }
    ll root=-1;
    for (ll i=1; i<=n; i++) if (adj[i].size()>2) root=i;
    if (root!=-1) 
    {
        cout<<adj[root].size()<<" "<<(adj[root].size()+1)/2;
        return;
    }
    else 
    {
        cout<<2<<" "<<1;
    }
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}