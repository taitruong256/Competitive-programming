#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;
vector<pair<ll, ll>> adj[500005];
ll n, m, ans=0, cnt=0;
bool vis[500005];

void dfs(ll u)
{
    vis[u]=true;
    ll sz=adj[u].size();
    for (auto [v, c]: adj[u]) ans+=c*(sz-1);
    cnt+=sz*(sz-1)/2;
    for (auto [v, c]: adj[u]) if (vis[v]==false) dfs(v);
}

void solve()
{
    cin>>n>>m;
    for (ll i=0; i<m; i++)
    {
        ll u, v, c; cin>>u>>v>>c;
        adj[u].push_back({v, c});
        adj[v].push_back({u, c});
    }
    for (ll i=1; i<=n; i++) if (vis[i]==false) dfs(i);
    if (cnt>0) cout<<(ans+cnt-1)/cnt; 
    else cout<<0<<endl;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}