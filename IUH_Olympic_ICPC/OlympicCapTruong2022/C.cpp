#include <bits/stdc++.h>
#include <ext/pb_ds/assoc_container.hpp>
#include <ext/pb_ds/tree_policy.hpp>
using namespace std;
using namespace __gnu_pbds;
#define ll long long
#define ordered_set tree<ll, null_type, less<ll>, rb_tree_tag, tree_order_statistics_node_update>
#define endl '\n'
const ll mod = 1e9+7;
const ll inf = 1e9;

ll luythua(ll x, ll n)
{
    ll p=1;
    for (ll i=1; i<=n; i++) p=(p*x)%mod;
    return p;
}

void solve()
{
    ll n, k; cin>>n>>k;
    ll ans=luythua(3, n*n-k);       cout<<ans<<endl;
    for (ll i=0; i<(1<<(2*n)); i++)
    {
        ll hang=0, cot=0;
        for (ll j=0; j<n; j++) if (i&(1<<j)) ++hang;
        for (ll j=n; j<2*n; j++) if (i&(1<<j)) ++cot;
        if ((hang+cot)%2==0) ans=(ans-luythua(3, (n-hang)*(n-cot)-k)+mod)%mod;
        else ans=(ans+luythua(3, (n-hang)*(n-cot)-k))%mod;
    }
    cout<<ans;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}