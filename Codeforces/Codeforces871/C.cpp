#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll inf = 1e18;
const ll mod = 1e9+7;

void solve()
{
    ll n; cin>>n;
    map<string, ll> val;
    for (ll i=1; i<=n; i++)
    {
        ll x;
        string y;
        cin>>x>>y;
        if (val.find(y)==val.end()) val[y]=x;
        else val[y]=min(val[y], x);
    }
    ll ans=1e18;
    if (val.find("00")!=val.end() && val.find("11")!=val.end()) ans=min(ans, val["00"]+val["11"]);
    if (val.find("01")!=val.end() && val.find("10")!=val.end()) ans=min(ans, val["01"]+val["10"]);
    if (val.find("11")!=val.end()) ans=min(ans, val["11"]);
    if (ans==1e18) ans=-1;
    cout<<ans<<endl;
    // for (auto [x, y]: val) cout<<x<<" "<<y<<" "<<endl; cout<<endl;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    ll t; cin>>t;
    while (t--) solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}