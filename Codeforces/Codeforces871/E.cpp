#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll inf = 1e18;
const ll mod = 1e9+7;
ll a[1005][1005], n, m, ans, now;

void loang(ll x, ll y)
{
    if (a[x][y]==0) return;
    now+=a[x][y];
    a[x][y]=0;
    loang(x+1, y);
    loang(x-1, y);
    loang(x, y+1);
    loang(x, y-1);
}

void solve()
{
    cin>>n>>m;
    for (ll i=1; i<=n; i++)
        for (ll j=1; j<=m; j++) cin>>a[i][j];
    
    ans=0;
    for (ll i=1; i<=n; i++)
        for (ll j=1; j<=m; j++)
            if (a[i][j]>0)
            {
                now=0;
                loang(i, j);
                ans=max(ans, now);
            }
    cout<<ans<<endl;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    ll t; cin>>t;
    while (t--) solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}