#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;

void solve()
{
    ll n, m; cin>>n>>m;
    ll ans[n+5];
    for (ll i=1; i<=n; i++) ans[i]=-1;
    set<ll> st1, st2;
    for (ll i=1; i<=n; i++) st1.insert(i);
    for (ll i=1; i<=m; i++)
    {
        ll p; cin>>p;
        if (st1.empty()) continue;
        if (st2.find(p)==st2.end())
        {
            ll x=*st1.rbegin();
            ans[x]=i;
            st1.erase(x);
        }
        st2.insert(p);
    }
    for (ll i=1; i<=n; i++) cout<<ans[i]<<" "; cout<<endl;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    ll t; cin>>t;
    while (t--) solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}