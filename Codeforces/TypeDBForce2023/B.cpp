#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;

void solve()
{
    ll n; cin>>n;
    map<ll, ll> uoc;
    ll i=2; 
    while (n>1)
    {
        while (n%i==0) ++uoc[i], n/=i;
        ++i;
        if (i*i>n) break;
    }
    if (n>1) ++uoc[n];
    ll ans=0;
    while (!uoc.empty())
    {
        ll mx=1e18;
        for (auto i: uoc) if (i.second!=0) mx=min(mx, i.second);
        if (mx==1e18) break;
        ll res=1;
        for (auto &i: uoc) if (i.second!=0) 
        {
            res*=i.first;
            i.second-=mx;
        }
        ans+=res*mx;
    }
    cout<<ans<<endl;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    ll t; cin>>t;
    while (t--) solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}