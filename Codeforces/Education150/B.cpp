#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;

void solve()
{
    ll n; cin>>n;
    ll a[n+5];
    for (ll i=1; i<=n; i++) cin>>a[i];
    vector<ll> v1, v2;
    bool check=true;
    string ans="";
    for (ll i=1; i<=n; i++)
    {
        if (check==true)
        {
            if (v1.empty()) ans+="1", v1.push_back(a[i]);
            else 
            {
                if (v1.back()<=a[i]) ans+="1", v1.push_back(a[i]);
                else
                {
                    if (a[i]<=v1.front()) check=false, ans+="1", v2.push_back(a[i]);
                    else ans+="0";
                } 
            }
        }
        else
        {
            if (v2.back()<=a[i] && a[i]<=v1.front()) ans+="1", v2.push_back(a[i]);
            else ans+="0";
        }
    }
    cout<<ans<<endl;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    ll t; cin>>t;
    while (t--) solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}