#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll maxn = 200005;
const ll mod = 1e9+7;

void solve()
{
    ll n; cin>>n;
    vector<ll> v;
    ll diff=0;
    for (ll i=1; i<=n; i++)
    {
        ll x; cin>>x;
        if (v.empty()) v.push_back(x);
        else if (v.back()!=x) diff+=abs(v.back()-x), v.push_back(x);
    }  
    if (diff==0)
    {
        cout<<1<<endl;
        return;
    }
    else 
    {
        ll ans=2;
        for (ll i=1; i<v.size()-1; i++)
            if (v[i]>v[i-1] && v[i]>v[i+1]) ++ans;
            else if (v[i]<v[i-1] && v[i]<v[i+1])  ++ans;
        cout<<ans<<endl;
    }
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    ll t; cin>>t;
    while (t--) solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}