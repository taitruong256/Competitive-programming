#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;

void solve()
{
    ll n, x, y; cin>>n>>x;
    deque<ll> dq[5];
    for (ll i=1; i<=n; i++) cin>>y, dq[1].push_back(y);
    for (ll i=1; i<=n; i++) cin>>y, dq[2].push_back(y);
    for (ll i=1; i<=n; i++) cin>>y, dq[3].push_back(y);
    ll ans=0;
    while (!dq[1].empty() && (dq[1].front()|x)==x) ans|=dq[1].front(), dq[1].pop_front();
    while (!dq[2].empty() && (dq[2].front()|x)==x) ans|=dq[2].front(), dq[2].pop_front();
    while (!dq[3].empty() && (dq[3].front()|x)==x) ans|=dq[3].front(), dq[3].pop_front();
    if (ans==x) cout<<"YES\n";
    else cout<<"NO\n";
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    ll t; cin>>t;
    while (t--) solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}