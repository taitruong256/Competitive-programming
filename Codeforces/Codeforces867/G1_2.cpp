#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll inf = 1e18;
const ll mod = 1e9+7;
const ll maxn= 1e6;
vector<ll> uoc[maxn+5];
ll cnt[1000005];

void solve()
{
    ll n; cin>>n;
    ll a[n+5];
    ll ans=0;
    set<ll> st;
    for (ll i=1; i<=n; i++) cin>>a[i], ++cnt[a[i]], st.insert(a[i]);
    for (auto i: st)
        for (auto j: uoc[i]) if (i%(j*j)==0)
        {
            if (j==1) ans+=cnt[i]*(cnt[i]-1)*(cnt[i]-2);
            else ans+=cnt[i]*cnt[i/j]*cnt[i/j/j];
        }
    cout<<ans<<endl;
    for (ll i=1; i<=n; i++) --cnt[a[i]];
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    for (ll i=1; i<=maxn; i++)
        for (ll j=i; j<=maxn; j+=i) uoc[j].push_back(i);
    ll t; cin>>t;
    while (t--) solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}