#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll inf = 1e18;
const ll mod = 1e9+7;

void solve()
{
    ll n; cin>>n;
    string s; cin>>s; s=" "+s;
    if (n%2==1)
    {
        cout<<-1<<endl;
        return;
    }
    map<char, ll> cnt;
    for (ll i=1; i<=n; i++) ++cnt[s[i]];
    for (auto [x, y]: cnt) if (y>n/2)
    {
        cout<<-1<<endl;
        return;
    }
    cnt.clear();
    for (ll i=1; i<=n/2; i++) if (s[i]==s[n-i+1]) ++cnt[s[i]];
    ll sum=0, mx=0;
    for (char c='a'; c<='z'; c++) sum+=cnt[c], mx=max(mx, cnt[c]);
    cout<<max(mx, (sum+1)/2)<<endl;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    ll t; cin>>t;
    while (t--) solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}