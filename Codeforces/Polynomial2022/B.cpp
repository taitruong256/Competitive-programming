#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;

void solve()
{
    ll n, m, k; cin>>n>>m>>k;
    ll x=(n+k-1)/k, cnt=0;
    ll a[m+5];
    bool check=true;
    for (ll i=1; i<=m; i++)
    {
        cin>>a[i];
        if (a[i]>x) check=false;
        if (a[i]==x) ++cnt;
    }       
    if (check==false)
    {
        cout<<"NO\n";
        return;
    }
    if (cnt<=(n-1)%k+1) cout<<"YES\n";
    else cout<<"NO\n";
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    ll t; cin>>t;
    while (t--) solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}