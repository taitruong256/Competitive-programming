#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define ld long double
#define endl '\n'
const ll mod = 1e9+7;

void solve()
{
    ll n; cin>>n;
    map<ll, ll> doc, ngang, cheo1, cheo2;
    pair<ll, ll> a[n+5];
    for (ll i=1; i<=n; i++)
    {
        cin>>a[i].first>>a[i].second;
        ++doc[a[i].first];
        ++ngang[a[i].second];
        ++cheo1[a[i].first-a[i].second];
        ++cheo2[a[i].first+a[i].second];
    }
    ll ans=0;
    for (auto [x, y]: doc) ans+=y*(y-1);
    for (auto [x, y]: ngang) ans+=y*(y-1);
    for (auto [x, y]: cheo1) ans+=y*(y-1);
    for (auto [x, y]: cheo2) ans+=y*(y-1);
    cout<<ans<<endl;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    ll t; cin>>t;
    while (t--) solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}