#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;

void solve()
{
    string s; cin>>s;
    map<char, ll> cnt;
    for (auto c: s) ++cnt[c];
    string s1, s2, s3;
    for (auto i: cnt) 
        if (i.second%2==0)
            for (ll j=0; j<i.second; j++) s1.push_back(i.first);
        else 
            for (ll j=0; j<i.second-1; j++) s1.push_back(i.first);
    for (auto i: cnt) if (i.second%2==1) s1.push_back(i.first);
    s2=s1;
    reverse(s2.begin(), s2.end());
    cout<<s1+s2<<endl;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    ll t; cin>>t;
    while (t--) solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}