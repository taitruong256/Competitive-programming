#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;

void solve()
{
    ll n, k; cin>>n>>k;
    if (k>=(n+1)/2)
    {
        for (ll i=n; i>=n-k+2; i--) cout<<i<<" ";
        for (ll i=1; i<=n-k+1; i++) cout<<i<<" "; 
        cout<<endl; 
    }
    else 
    {
        ll ans[2*n+5];
        for (ll i=1; i<=n; i++) ans[i]=0;
        ll x=n;
        for (ll i=1; i<=n; i++) if (ans[i]==0)
        {
            ans[i]=x;
            ans[i+k-1]=n+1-x;
            --x;
        }
        for (ll i=1; i<=n; i++) cout<<ans[i]<<" "; cout<<endl;
    }
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    ll t; cin>>t;
    while (t--) solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}