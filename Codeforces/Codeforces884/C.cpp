#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;

void solve()
{
    ll n; cin>>n;
    deque<ll> dq;
    ll ans=-1e18;
    for (ll i=1; i<=n; i++)
    {
        ll x; cin>>x;
        ans=max(ans, x);
        dq.push_back(x);
        ll sz=dq.size();
        if (sz>=3 && dq[sz-1]<0 && dq[sz-2]<0 && dq[sz-3]<0)
            for (ll j=0; j<3; j++) dq.pop_back();
    }
    ll sum=0;
    for (ll i=0; i<dq.size(); i+=2)
    {
        if (dq[i]>0) sum+=dq[i], ans=max(ans, sum);
        else sum=0;
    }
    sum=0;
    for (ll i=1; i<dq.size(); i+=2)
    {
        if (dq[i]>0) sum+=dq[i], ans=max(ans, sum);
        else sum=0;
    }
    cout<<ans<<endl;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    ll t; cin>>t;
    while (t--) solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}