#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;

void solve()
{
    ll n; cin>>n;
    ll a[n+5];
    for (ll i=1; i<=n; i++) cin>>a[i];
    a[0]=1e9;
    a[n+1]=1e9;
    ll median=(n+1)/2, pos=1;
    for (ll i=1; i<=n; i++) if (a[i]==median) pos=i;
    ll truoc=0, sau=0;
    ll x=median-1;
    for (ll i=pos-1; i>=1; i--)
    {
        if (a[i]!=x) 
        {
            if (a[i]!=1) ++truoc;
        }
        else --x;
    }
    for (ll i=pos+1; i<=n; i++)
    {
        if (a[i]!=x) ++sau;
        else ++x;
    }
    ll ans=min(truoc, sau);
    truoc-=ans;
    sau-=ans;
    cout<<ans+(truoc+sau+1)/2<<endl;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    ll t; cin>>t;
    while (t--) solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}