#define ll long long
#define endl '\n'
const ll mod = 1e9+7;

void solve()
{
    ll n, k; cin>>n>>k;
    ll ans[n+5];
    ans[1]=1;
    ll s=1;
    for (ll i=2; i<=n; i++) 
    {
        ans[i]=i*(i+1)/2+1;
    }
    for (ll i=n; i>=1; i--) 
    {
        if (k>=i) k-=i, ans[i]=i*(i+1)+1;
        else ans[i]=-i;
    }


    ll am=0, duong=0;
    for (ll i=1; i<=n; i++) 
        for (ll j=1; j<=i; j++)
        {
            ll sum=0;
            for (ll k=j; k<=i; k++) sum+=ans[k];
            if (sum<0) ++am;
            else ++duong;
        }
    cout<<duong<<" "<<am<<endl;


    for (ll i=1; i<=n; i++) cout<<ans[i]<<" "; cout<<endl;
}

