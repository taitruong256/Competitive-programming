#include <bits/stdc++.h>
using namespace std;
#define endl '\n'
typedef long long ll;

void solve()
{
    ll n; cin>>n;
    ll a[n+5];
    map<ll, ll> cnt; 
    cnt.clear();
    for (ll i=1; i<=n; i++)
    {
        cin>>a[i];
        ++cnt[a[i]];
    }
    for (auto it: cnt) if (it.second>=3) 
    {
        cout<<it.first<<endl;
        return;
    }
    cout<<-1<<endl;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    ll tc=1; cin>>tc;
    for (ll t=1; t<=tc; t++) solve();
    return 0;
}