#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;

void solve()
{
    ll n; cin>>n; 
    ll a[n+5];
    for (ll i=1; i<=n; i++) cin>>a[i];
    ll mx=-1e18;
    ll mn=1e18;
    for (ll i=1; i<=n; i++) mx=max(mx, a[i]);
    for (ll i=1; i<=n; i++) mn=min(mn, a[i]);
    ll cntmax=0, cntmin=0;
    for (ll i=1; i<=n; i++) if (a[i]==mx) ++cntmax;
    for (ll i=1; i<=n; i++) if (a[i]==mn) ++cntmin;
    if (mx==mn) cout<<(n-1)*n<<endl;
    else cout<<2*cntmax*cntmin<<endl;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    ll t; cin>>t;
    while (t--) solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}