#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;

void solve()
{
    ll n; cin>>n;
    multiset<ll> ms;
    for (ll i=1; i<=n; i++)
    {
        ll x; cin>>x;
        ms.insert(x);
    }
    ll ans=0;
    while (!ms.empty())
    {
        ll x=*ms.begin(); ms.erase(ms.find(x));
        while (!ms.empty())
        {
            auto it=ms.lower_bound(x+1);
            if (it==ms.end()) break;
            ll y=*it;
            if (y==x+1) ms.erase(ms.find(x+1)), ++x;
            else break;
        }
        ++ans;
    }
    cout<<ans<<endl;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    ll t; cin>>t;
    while (t--) solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}