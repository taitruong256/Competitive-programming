#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;

void solve()
{
    ll n, m; cin>>n>>m;
    vector<vector<ll>> A(n+5, vector<ll>(n+5));
    for (ll i=0; i<n; i++) cin>>A[0][i];
    for (ll i=1; i<=m; i++)
    {
        A[i]=A[i-1];
        ll pos, val; cin>>pos>>val;
        --pos;
        A[i][pos]=val;
    }
    

    ll ans=0;
    for (ll i=0; i<=m-1; i++)
        for (ll j=i+1; j<=m; j++)
        {
            vector<ll> v1=A[i], v2=A[j];
            set<ll> st;
            for (ll k=0; k<n; k++) st.insert(v1[k]);
            for (ll k=0; k<n; k++) st.insert(v2[k]);
            ans+=st.size();
        }
    cout<<ans<<endl;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    ll t; cin>>t;
    while (t--) solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}