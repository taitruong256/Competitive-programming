#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll maxn = 200005;
const ll mod = 1e9+7;

void solve()
{
    string s; cin>>s;
    ll n=s.size();
    char last=' ';
    for (ll i=0; i<n; i++)
    {
        if (s[i]!='?') last=s[i];
        else if (last=='0') s[i]='0';
    }
    last=' ';
    for (ll i=n; i>=0; i--)
    {
        if (s[i]!='?') last=s[i];
        else if (last=='0') s[i]='0';
    }
    for (ll i=0; i<n; i++) if (s[i]=='?') s[i]='1';
    cout<<s<<endl;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    ll t; cin>>t;
    while (t--) solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}