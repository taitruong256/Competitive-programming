#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
#define cout_return(x) return void(cout<<(x)<<endl)
const ll inf = 1e18;
const ll mod = 1e9+7;

ll tinh(ll n)
{
    if (n%2==1) return ((n+1)/2)*((n+1)/2);
    else return (n/2)*(n/2+1);
}

void solve()
{
    string s; cin>>s;
    ll n=s.size();
    s=s+s+" ";
    ll ans=0, cnt=0;
    for (ll i=0; i<s.size(); i++)
    {
        if (s[i]=='1') ++cnt;
        else ans=max(ans, tinh(cnt)), cnt=0;
    }
    ans=min(ans, n*n);
    cout<<ans<<endl;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    ll t; cin>>t;
    while (t--) solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}