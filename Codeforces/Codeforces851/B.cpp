#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;

ll sum_digit(ll n)
{
    ll ans=0;
    while (n>0)
    {
        ans+=n%10;
        n/=10;
    }
    return ans;
}

void solve()
{
    ll n; cin>>n;
    for (ll i=0; i<=n; i++) if (abs(sum_digit(i)-sum_digit(n-i))<=1)
    {
        cout<<i<<" "<<n-i<<endl;
    }
    cout<<endl;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    ll t; cin>>t;
    while (t--) solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}