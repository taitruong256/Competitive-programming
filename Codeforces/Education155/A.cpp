#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define ld long double
#define endl '\n'
const ll mod = 1e9+7;

void solve()
{
    ll n; cin>>n;
    ll s[n+5], e[n+5];
    for (ll i=1; i<=n; i++) cin>>s[i]>>e[i];
    ll cnt[n+5];
    cnt[1]=e[1];
    for (ll i=2; i<=n; i++) 
        if (s[i]>=s[1]) cnt[i]=e[i];
        else cnt[i]=0;
    map<ll, ll> val;
    ++val[cnt[1]];
    for (ll i=2; i<=n; i++) 
    {
        ++val[cnt[i]];
        if (cnt[i]>cnt[1] || val[cnt[1]]>1)
        {
            cout<<-1<<endl;
            return;
        }
    }
    cout<<s[1]<<endl;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    ll t; cin>>t;
    while (t--) solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}