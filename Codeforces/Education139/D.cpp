#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;
ll minprime[10000005];

void solve()
{
    ll x, y; cin>>x>>y;
    ll d=y-x;
    if (__gcd(x, y)!=1)
    {
      cout<<0<<endl;
      return;
    }
    if (y-x==1)
    {
      cout<<-1<<endl;
      return;
    }
    ll ans=1e9;
    while (d>1)
    {
      ll p=minprime[d];
      ans=min(ans, p-x%p);
      assert(ans!=1e9);
      while (d%p==0) d/=p;
    }
    cout<<ans<<endl;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    for (ll i=2; i<=10000000; i++) if (minprime[i]==0)
      for (ll j=i*i; j<=10000000; j+=i) if (minprime[j]==0) minprime[j]=i;
    for (ll i=1; i<=10000000; i++) if (minprime[i]==0) minprime[i]=i;
    ll t; cin>>t;
    while (t--) solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}