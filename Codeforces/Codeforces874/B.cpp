#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll maxn = 200005;
const ll mod = 1e9+7;
ll a[100005], b[100005], id[100005], ans[100005];

bool comp(ll u, ll v)
{
    return a[u]<a[v];
}

void solve()
{
    ll n, k; cin>>n>>k; 
    for (ll i=1; i<=n; i++) cin>>a[i], id[i]=i;
    sort(id+1, id+n+1, comp);
    for (ll i=1; i<=n; i++) cin>>b[i]; 
    sort(b+1, b+n+1);
    for (ll i=1; i<=n; i++) ans[id[i]]=b[i];
    for (ll i=1; i<=n; i++) cout<<ans[i]<<" "; cout<<endl;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    ll t; cin>>t;
    while (t--) solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}