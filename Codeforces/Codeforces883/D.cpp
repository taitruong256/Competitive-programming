#include <bits/stdc++.h>
using namespace std;
#define ll long long
#define endl '\n'
const ll mod = 1e9+7;

long double dientich(long double d, long double h)
{
    return 0.5*d*h;
}

void solve()
{
    ll n, d, h; cin>>n>>d>>h;
    long double sum=0;
    ll a[n+5];
    for (ll i=1; i<=n; i++) cin>>a[i];
    a[n+1]=2e9;
    for (ll i=1; i<=n; i++)
    {
        if (a[i+1]-a[i]>=h) sum+=dientich(d, h);
        else 
        {
            long double h_=a[i+1]-a[i];
            long double d_=h_*d/h;
            sum+=dientich(d, h)-dientich(d-d_, h-h_);
        }
    }   
    cout<<fixed<<setprecision(9)<<sum<<endl;
}

int main()
{
    ios_base::sync_with_stdio(false); cin.tie(NULL);
    clock_t start = clock();
    #ifndef ONLINE_JUDGE
    freopen("_input.txt", "r", stdin);
    freopen("_output.txt", "w", stdout);
    #endif
    ll t; cin>>t;
    while (t--) solve();
    clock_t end = clock();
    cerr<<"Time: "<<fixed<<setprecision(10)<<double(end-start)/double(CLOCKS_PER_SEC)<<"\n";
    return 0;
}